local Tunnel = module("vrp","lib/Tunnel")-----------------------------------------------------------------------------------------------------------------------------------------
-- CONNECTION
-----------------------------------------------------------------------------------------------------------------------------------------
Creative = {}
Tunnel.bindInterface("pause",Creative)
vSERVER = Tunnel.getInterface("pause")
-----------------------------------------------------------------------------------------------------------------------------------------
-- VARIABLES
-----------------------------------------------------------------------------------------------------------------------------------------
local Pause = false
local SalaryTick = 0
local Cooldown = GetGameTimer()
local SalaryCooldown = GetGameTimer() + 60000
-----------------------------------------------------------------------------------------------------------------------------------------
-- FUNCTIONS
-----------------------------------------------------------------------------------------------------------------------------------------
local function IsPhoneOpen()
	if GetResourceState("lb-phone") ~= "started" then
		return false
	end

	local Success,Result = pcall(function()
		return exports["lb-phone"]:IsOpen()
	end)

	return Success and Result or false
end

local function ClosePause()
	Pause = false
	SetNuiFocus(false,false)
	TransitionFromBlurred(1000)
	TriggerEvent("hud:Active",true)
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- THREADSALARY
-----------------------------------------------------------------------------------------------------------------------------------------
CreateThread(function()
	while true do
		local Ped = PlayerPedId()
		if LocalPlayer.state.Active and GetEntityHealth(Ped) > 100 and not LocalPlayer.state.Arena and SalaryCooldown < GetGameTimer() then
			SalaryCooldown = GetGameTimer() + 60000
			SalaryTick = SalaryTick + 1

			if SalaryTick > 30 then
				SalaryTick = 0
				vSERVER.Salarys()
			end
		end

		Wait(30000)
	end
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- COMMAND
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterCommand("PauseBreak",function()
	local Ped = PlayerPedId()
	local isDead = GetEntityHealth(Ped) <= 101
	local isHandcuffed = LocalPlayer["state"]["Handcuff"]
	
	if not LocalPlayer.state.Arena and not IsPhoneOpen() and not Pause and not IsPauseMenuActive() and Cooldown < GetGameTimer() and not isDead and not isHandcuffed then
		Pause = true
		SetNuiFocus(true,true)
		TransitionToBlurred(1000)
		SetCursorLocation(0.5,0.5)
		Cooldown = GetGameTimer() + 5000
		SendNUIMessage({ Action = "Open" })
		TriggerEvent("hud:Active",false)
	end
end)
