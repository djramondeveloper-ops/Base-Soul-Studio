-- Append a line to a string buffer
function append(buffer, ...)
    return buffer .. table.concat({...}, "\n")
end

-- Load a file from a resource
function loadFile(resourceName, filePath)
    return LoadResourceFile(resourceName, filePath)
end

-- ============================================================
--  APPEND HELPERS (inject content into existing resource files)
-- ============================================================

local function makeAppendHelper(pattern, suffix)
    return function(content, injection)
        content = content:strtrim()
        return content:gsub(pattern, function(match)
            return match .. "\n" .. injection .. suffix
        end)
    end
end

