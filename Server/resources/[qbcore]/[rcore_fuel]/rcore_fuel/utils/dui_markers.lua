-- utils/dui_markers.lua
-- DUI-based 3D marker helpers for fuel pump displays.
-- These markers render the live pump price/liter data above dispensers via DUI textures.

local ActiveDuiMarkers = {}

--- Create or update a DUI marker entry for a pump.
---@param identifier string  unique pump DUI identifier (e.g. "pump_shopId_dispenserId")
---@param position   vector3
---@param data       table   { fuelType, price, liters }
function SetDuiMarker(identifier, position, data)
    ActiveDuiMarkers[identifier] = {
        position = position,
        data     = data,
        active   = true
    }
end

--- Remove a DUI marker by identifier.
---@param identifier string
function RemoveDuiMarker(identifier)
    ActiveDuiMarkers[identifier] = nil
end

--- Returns all currently active DUI markers.
---@return table
function GetAllDuiMarkers()
    return ActiveDuiMarkers
end
