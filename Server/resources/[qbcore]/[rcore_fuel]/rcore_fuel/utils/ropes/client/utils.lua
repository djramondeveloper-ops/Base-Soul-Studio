local identifierSequence = 0

function GenerateRandomIdentifier()
    identifierSequence = identifierSequence + 1
    local charset = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
    local result = ""
    local seed = GetPlayerServerId(PlayerId()) + GetGameTimer()
    for _ = 1, 12 do
        seed = (seed * 214013 + 2531011) % 2147483648
        local index = math.floor(seed / 65536.0) % #charset + 1
        result = result .. string.sub(charset, index, index)
    end
    return result .. string.format("%x", identifierSequence)
end
