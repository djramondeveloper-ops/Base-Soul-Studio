RegisterNetEvent("rcore_rope:sync:fetch", function(ropeCache)
    RopeCache = ropeCache
end)

RegisterNetEvent("rcore_rope:sync:AddToCache", function(ropeEntry)
    if IsRopeRequestCancelled(ropeEntry.ropeHandler) then
        TriggerServerEvent("rcore_rope:sync:RemoveFromCache", ropeEntry.ropeHandler)
        return
    end
    -- A duplicate acknowledgement must not lose the existing native rope handle.
    if RopeCache[ropeEntry.ropeHandler] then return end
    RopeCache[ropeEntry.ropeHandler] = ropeEntry
    RefreshRopes()
end)

RegisterNetEvent("rcore_rope:sync:RemoveFromCache", function(ropeHandler)
    RemoveRopeFromHandler(ropeHandler)
end)

