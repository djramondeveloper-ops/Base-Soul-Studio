function RemoveRopeFromHandler(ropeHandler)
    if ropeHandler == nil then
        return
    end
    local ropeData = RopeCache[ropeHandler]
    if not ropeData then
        return
    end
    if ropeData.ropeEntity then
        DeleteRope(ropeData.ropeEntity)
    end
    -- FIX 1: nil the cache entry FIRST, then check if any ropes remain
    -- (was checking before removal so the condition was always true for the last rope)
    RopeCache[ropeHandler] = nil
    if not IsAnyRopeActive() then
        -- No ropes left -- signal texture cleanup
        WasMemoryClearedSwitch = true
        TriggerEvent("rcore_fuel:unloadedRopeTextures")
    end
end

function IsAnyRopeActive()
    for _, ropeData in pairs(RopeCache) do
        if ropeData.ropeEntity then
            return true
        end
    end
    return false
end

AddEventHandler("onResourceStop", function(resourceName)
    if resourceName ~= GetCurrentResourceName() then
        return
    end

    for _, ropeData in pairs(RopeCache) do
        if ropeData and ropeData.ropeEntity then
            DeleteRope(ropeData.ropeEntity)
            ropeData.ropeEntity = nil
        end
    end
end)
