local pendingCallbacks = {}
local callbackId = 0

function callCallback(callbackName, callbackFn, ...)
    local requestId = callbackId
    pendingCallbacks[requestId] = callbackFn
    TriggerServerEvent("rcore_fuel:callCallback", callbackName, requestId, ...)

    -- Network/provider failures should not leave callbacks retained forever.
    SetTimeout(30000, function()
        local cb = pendingCallbacks[requestId]
        if cb then
            pendingCallbacks[requestId] = nil
            print(string.format("[rcore_fuel] Callback '%s' timed out.", tostring(callbackName)))
            cb(false)
        end
    end)

    if callbackId < 65535 then
        callbackId = callbackId + 1
    else
        callbackId = 0
    end
end

RegisterNetEvent("rcore_fuel:callback")
AddEventHandler("rcore_fuel:callback", function(id, ...)
    if pendingCallbacks[id] == nil then
        return
    end
    -- FIX #8: clear the entry before calling to prevent memory leak
    local cb = pendingCallbacks[id]
    pendingCallbacks[id] = nil
    cb(...)
end)
