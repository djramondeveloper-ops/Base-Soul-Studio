RegisterNetEvent("rcore_fuel:showFuelRequest", function(requestText, missionId)
    OpenOptionalAcceptMenu(requestText, function(choice)
        if choice == "yes" then
            TriggerServerEvent("rcore_fuel:acceptedRefuelMission", missionId)
        else
            -- FIX 11: treat "no" AND menu-close (nil choice) both as a refusal
            -- so the server never gets stuck with a mission locked in pending state
            TriggerServerEvent("rcore_fuel:playerRefusedMission", missionId)
        end
    end)
end)
