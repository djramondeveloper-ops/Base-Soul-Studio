if Config.EnableItemShop then
    CreateThread(function()
        local markerStyle = Config.ItemShopMarkerStyle or {}

        for _, shopPosition in pairs(Config.ItemShopPosition or {}) do
            local shopMarker = createMarker()
            shopMarker.setRenderDistance(10)
            shopMarker.setPosition(shopPosition)
            shopMarker.setRotation(markerStyle.rotate or false)
            shopMarker.setFaceCamera(markerStyle.faceCamera or false)
            shopMarker.setType(markerStyle.type or 29)
            shopMarker.setInRadius(2.5)

            if Config.Debug then
                local debugText = create3DText("marker shop")
                debugText.setPosition(shopPosition)
            end

            shopMarker.setColor(markerStyle.color or { r = 0, g = 255, b = 0, a = 100 })
            shopMarker.setKeys({ 38 })
            shopMarker.on("enter", function()
                ShowHelpNotification(_U("interact_key"), false, true, 10000)
            end)
            shopMarker.on("leave", function() end)
            shopMarker.on("key", function()
                OpenShopMenu()
            end)
        end
    end, "markers for item shop")
end
