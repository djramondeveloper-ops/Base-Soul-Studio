if Config.TargetZoneType == 0 then
    CreateThread(function()
        while true do
            Wait(1000)

            local playerCoords = GetEntityCoords(PlayerPedId())

            for _, shop in pairs(Config.ShopList) do
                if #(shop.blipPosition - playerCoords) <= 100 then
                    for _, pump in pairs(shop.pumpPosition) do
                        if DoesEntityExist(pump.entity) then
                            if #(pump.pos - playerCoords) < 2 then
                                if not pump.entered then
                                    pump.entered = true

                                    if IsPlayerReadyToPump then  -- FIX 2: IsPlayerReadyToPump is a boolean, not a function
                                        ShowHelpNotification(_U("put_away_gun"), false, true, 10000)
                                    else
                                        ShowHelpNotification(_U("take_gun"), false, true, 10000)
                                    end
                                end
                            elseif pump.entered then
                                pump.entered = false
                            end
                        end
                    end
                end
            end
        end
    end, "notification for fuel pump")
end
