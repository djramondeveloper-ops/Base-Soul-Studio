local function trimContent(content)
  return content:strtrim()
end

local function insertAfterPattern(content, pattern, injection, suffix)
  content = trimContent(content)

  return content:gsub(pattern, function(match)
    return match .. "\n" .. injection .. (suffix or "\n")
  end)
end

function append(content, ...)
  return content .. table.concat({ ... }, "\n")
end

function loadFile(resourceName, filePath)
  return LoadResourceFile(resourceName, filePath)
end

function appendQB(content, injection)
  return insertAfterPattern(content, "QBShared.Items = {", injection, "\n")
end

